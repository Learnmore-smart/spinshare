import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";

export const CLAUDE_HOOK_EVENTS = [
  "UserPromptSubmit",
  "MessageDisplay",
  "Stop",
  "StopFailure",
] as const;

type ClaudeHookEvent = (typeof CLAUDE_HOOK_EVENTS)[number];
const SPINSHARE_HOOK_SCRIPT = "spinshare-hook.cjs";
const SPINSHARE_STATUSLINE_SCRIPT = "spinshare-statusline.cjs";

export interface ClaudeCodeAdapterFile {
  filePath: string;
  content: string;
  executable: boolean;
}

export interface ClaudeCodeAdapterPlan {
  settingsPath: string;
  backupPath: string;
  scriptDir: string;
  stateFilePath: string;
  hookCommand: string;
  statusLineCommand: string;
  files: ClaudeCodeAdapterFile[];
}

export interface BuildClaudeCodeAdapterPlanOptions {
  homeDir?: string;
  storageRoot: string;
  baseUrl: string;
}

interface ClaudeSettings {
  [key: string]: unknown;
  statusLine?: unknown;
  hooks?: Record<string, Array<Record<string, unknown>>>;
}

interface ClaudeCodeAdapterFileSystem {
  mkdir(filePath: string, options: { recursive: true }): Promise<unknown>;
  readFile(filePath: string, encoding: "utf8"): Promise<string>;
  writeFile(
    filePath: string,
    content: string,
    options?: { mode?: number; encoding?: "utf8" },
  ): Promise<unknown>;
  copyFile(from: string, to: string): Promise<unknown>;
  access(filePath: string): Promise<unknown>;
  chmod?(filePath: string, mode: number): Promise<unknown>;
  rm?(
    filePath: string,
    options: { recursive?: boolean; force?: boolean },
  ): Promise<unknown>;
}

export interface InstallClaudeCodeAdapterOptions
  extends BuildClaudeCodeAdapterPlanOptions {
  enabled?: boolean;
  fileSystem?: ClaudeCodeAdapterFileSystem;
}

export interface RemoveClaudeCodeAdapterOptions
  extends BuildClaudeCodeAdapterPlanOptions {
  fileSystem?: ClaudeCodeAdapterFileSystem;
}

function trimBaseUrl(baseUrl: string): string {
  return baseUrl.replace(/\/+$/, "");
}

function commandPath(filePath: string): string {
  return filePath.replace(/\\/g, "/");
}

function nodeCommand(filePath: string): string {
  return `node "${commandPath(filePath)}"`;
}

export function defaultClaudeCodeAdapterStorageRoot(
  env: Record<string, string | undefined> = process.env,
  homedir: string = os.homedir(),
): string {
  const configBase =
    env.XDG_CONFIG_HOME ?? env.APPDATA ?? path.join(homedir, ".config");
  return path.join(configBase, "spinshare", "claude-code-adapter");
}

function defaultCredentialFileSnippet(): string {
  return `
function defaultCredentialFilePath() {
  const home = os.homedir();
  const configBase = process.env.XDG_CONFIG_HOME || process.env.APPDATA || path.join(home, ".config");
  return path.join(configBase, "spinshare", "credentials.json");
}

function readToken() {
  if (process.env.SPINSHARE_TOKEN && process.env.SPINSHARE_TOKEN.length > 0) {
    return process.env.SPINSHARE_TOKEN;
  }
  try {
    const parsed = JSON.parse(fs.readFileSync(defaultCredentialFilePath(), "utf8"));
    return typeof parsed.token === "string" && parsed.token.length > 0 ? parsed.token : null;
  } catch {
    return null;
  }
}
`;
}

function hookScript(baseUrl: string, stateFilePath: string): string {
  return `// Generated by SpinShare. Do not edit.
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const baseUrl = ${JSON.stringify(trimBaseUrl(baseUrl))};
const stateFile = ${JSON.stringify(stateFilePath)};
const eventName = process.argv[2] || "";

${defaultCredentialFileSnippet()}

function ensureStateDir() {
  fs.mkdirSync(path.dirname(stateFile), { recursive: true });
}

function readState() {
  try {
    return JSON.parse(fs.readFileSync(stateFile, "utf8"));
  } catch {
    return null;
  }
}

function writeState(state) {
  ensureStateDir();
  fs.writeFileSync(stateFile, JSON.stringify(state), { encoding: "utf8", mode: 0o600 });
}

function clearState() {
  try {
    fs.rmSync(stateFile, { force: true });
  } catch {}
}

function readHookInput() {
  try {
    const raw = fs.readFileSync(0, "utf8");
    return raw.trim().length > 0 ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

function readSessionId() {
  const input = readHookInput();
  return typeof input.session_id === "string" && input.session_id.length > 0
    ? input.session_id
    : null;
}

const sessionId = readSessionId();

function stateMatchesSession(state) {
  return !sessionId || !state || !state.sessionId || state.sessionId === sessionId;
}

async function fetchAd(token) {
  const response = await fetch(baseUrl + "/api/ad", {
    headers: {
      accept: "application/json",
      authorization: "Bearer " + token,
    },
  });
  if (!response.ok) return null;
  const ad = await response.json();
  return ad && ad.adAvailable === true ? ad : null;
}

async function trackIfViewable(state) {
  if (!state || !state.campaignId || !state.startedAtMs) return;
  if (!stateMatchesSession(state)) return;
  const viewDurationMs = Date.now() - state.startedAtMs;
  if (viewDurationMs < 1) return;
  const token = readToken();
  if (!token) return;
  await fetch(baseUrl + "/api/track", {
    method: "POST",
    headers: {
      "content-type": "application/json",
      authorization: "Bearer " + token,
    },
    body: JSON.stringify({ campaignId: state.campaignId, viewDurationMs }),
  }).catch(() => {});
}

(async () => {
  const isPromptStart = eventName === "UserPromptSubmit";
  const isDisplayEvent = eventName === "MessageDisplay";
  if (isPromptStart || isDisplayEvent) {
    const current = readState();
    if (current && current.active === true) {
      if (!isPromptStart && stateMatchesSession(current)) return;
      clearState();
    }
    const token = readToken();
    if (!token) return;
    const ad = await fetchAd(token);
    if (ad) {
      writeState({
        active: true,
        campaignId: ad.campaignId,
        adText: ad.adText,
        destinationUrl: ad.destinationUrl,
        brandName: ad.brandName,
        sessionId,
        startedAtMs: Date.now(),
      });
    }
    return;
  }
  if (eventName === "Stop" || eventName === "StopFailure") {
    const state = readState();
    clearState();
    await trackIfViewable(state);
  }
})().catch(() => {});
`;
}

function statusLineScript(stateFilePath: string): string {
  return `// Generated by SpinShare. Do not edit.
const fs = require("node:fs");

const stateFile = ${JSON.stringify(stateFilePath)};

function osc8(url, text) {
  return "\\u001b]8;;" + url + "\\u0007" + text + "\\u001b]8;;\\u0007";
}

function accent(text) {
  return "\\u001b[1;36m" + text + "\\u001b[0m";
}

function readStatusLineInput() {
  try {
    const raw = fs.readFileSync(0, "utf8");
    return raw.trim().length > 0 ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

function readSessionId() {
  const input = readStatusLineInput();
  return typeof input.session_id === "string" && input.session_id.length > 0
    ? input.session_id
    : null;
}

const sessionId = readSessionId();

function stateMatchesSession(state) {
  return !sessionId || !state || !state.sessionId || state.sessionId === sessionId;
}

try {
  const state = JSON.parse(fs.readFileSync(stateFile, "utf8"));
  if (state && state.active === true && state.adText && stateMatchesSession(state)) {
    const text = "$ " + state.adText;
    const styledText = accent(text);
    process.stdout.write(state.destinationUrl ? osc8(state.destinationUrl, styledText) : styledText);
  }
} catch {}
`;
}

export function buildClaudeCodeAdapterPlan(
  options: BuildClaudeCodeAdapterPlanOptions,
): ClaudeCodeAdapterPlan {
  const homeDir = options.homeDir ?? os.homedir();
  const claudeDir = path.join(homeDir, ".claude");
  const scriptDir = options.storageRoot;
  const hookPath = path.join(scriptDir, "spinshare-hook.cjs");
  const statusLinePath = path.join(scriptDir, "spinshare-statusline.cjs");
  const stateFilePath = path.join(scriptDir, "state.json");
  return {
    settingsPath: path.join(claudeDir, "settings.json"),
    backupPath: path.join(claudeDir, "settings.spinshare-backup.json"),
    scriptDir,
    stateFilePath,
    hookCommand: nodeCommand(hookPath),
    statusLineCommand: nodeCommand(statusLinePath),
    files: [
      {
        filePath: hookPath,
        content: hookScript(options.baseUrl, stateFilePath),
        executable: false,
      },
      {
        filePath: statusLinePath,
        content: statusLineScript(stateFilePath),
        executable: false,
      },
    ],
  };
}

function asSettings(value: unknown): ClaudeSettings {
  return value && typeof value === "object" && !Array.isArray(value)
    ? { ...(value as ClaudeSettings) }
    : {};
}

function parseClaudeSettings(raw: string): unknown {
  const normalized = raw.charCodeAt(0) === 0xfeff ? raw.slice(1) : raw;
  return JSON.parse(normalized);
}

function hookHandler(plan: ClaudeCodeAdapterPlan, event: ClaudeHookEvent) {
  return {
    hooks: [{ type: "command", command: `${plan.hookCommand} ${event}` }],
  };
}

function hasCommand(
  groups: Array<Record<string, unknown>>,
  command: string,
): boolean {
  return groups.some((group) => {
    const hooks = group.hooks;
    return (
      Array.isArray(hooks) &&
      hooks.some(
        (hook) =>
          hook &&
          typeof hook === "object" &&
          (hook as { command?: unknown }).command === command,
      )
    );
  });
}

function hookCommandText(hook: unknown): string | null {
  return hook && typeof hook === "object"
    ? ((hook as { command?: unknown }).command as string | undefined) ?? null
    : null;
}

function isSpinShareHookCommand(command: unknown): boolean {
  return (
    typeof command === "string" &&
    command.toLowerCase().includes(SPINSHARE_HOOK_SCRIPT)
  );
}

function isSpinShareStatusLine(statusLine: unknown): boolean {
  return (
    statusLine !== null &&
    typeof statusLine === "object" &&
    !Array.isArray(statusLine) &&
    typeof (statusLine as { command?: unknown }).command === "string" &&
    ((statusLine as { command: string }).command)
      .toLowerCase()
      .includes(SPINSHARE_STATUSLINE_SCRIPT)
  );
}

function removeSpinShareHookCommands(
  group: Record<string, unknown>,
): Record<string, unknown> | null {
  const hooks = group.hooks;
  if (!Array.isArray(hooks)) {
    return group;
  }
  const filtered = hooks.filter(
    (hook) => !isSpinShareHookCommand(hookCommandText(hook)),
  );
  if (filtered.length === hooks.length) {
    return group;
  }
  if (filtered.length === 0) {
    return null;
  }
  return { ...group, hooks: filtered };
}

export function mergeClaudeCodeSettings(
  existing: unknown,
  plan: ClaudeCodeAdapterPlan,
): ClaudeSettings {
  const settings = asSettings(existing);
  const hooks =
    settings.hooks && typeof settings.hooks === "object" && !Array.isArray(settings.hooks)
      ? { ...settings.hooks }
      : {};

  for (const event of CLAUDE_HOOK_EVENTS) {
    const groups = Array.isArray(hooks[event])
      ? hooks[event]
          .map((group) => removeSpinShareHookCommands(group))
          .filter((group): group is Record<string, unknown> => group !== null)
      : [];
    const command = `${plan.hookCommand} ${event}`;
    if (!hasCommand(groups, command)) {
      groups.push(hookHandler(plan, event));
    }
    hooks[event] = groups;
  }

  return {
    ...settings,
    statusLine: { type: "command", command: plan.statusLineCommand, refreshInterval: 1 },
    hooks,
  };
}

function removeHookCommand(
  group: Record<string, unknown>,
  command: string,
): Record<string, unknown> | null {
  const hooks = group.hooks;
  if (!Array.isArray(hooks)) {
    return group;
  }
  const filtered = hooks.filter(
    (hook) =>
      !(
        hookCommandText(hook) === command ||
        isSpinShareHookCommand(hookCommandText(hook))
      ),
  );
  if (filtered.length === hooks.length) {
    return group;
  }
  if (filtered.length === 0) {
    return null;
  }
  return { ...group, hooks: filtered };
}

export function removeClaudeCodeSettings(
  existing: unknown,
  plan: ClaudeCodeAdapterPlan,
): ClaudeSettings {
  const settings = asSettings(existing);
  const cleaned: ClaudeSettings = { ...settings };
  const statusLine = cleaned.statusLine;
  if (
    isSpinShareStatusLine(statusLine) ||
    (statusLine &&
      typeof statusLine === "object" &&
      !Array.isArray(statusLine) &&
      (statusLine as { command?: unknown }).command === plan.statusLineCommand)
  ) {
    delete cleaned.statusLine;
  }

  const hooks =
    settings.hooks && typeof settings.hooks === "object" && !Array.isArray(settings.hooks)
      ? { ...settings.hooks }
      : {};

  for (const event of CLAUDE_HOOK_EVENTS) {
    const groups = Array.isArray(hooks[event]) ? hooks[event] : undefined;
    if (!groups) {
      continue;
    }
    const command = `${plan.hookCommand} ${event}`;
    const cleanedGroups = groups
      .map((group) => removeHookCommand(group, command))
      .filter((group): group is Record<string, unknown> => group !== null);
    if (cleanedGroups.length === 0) {
      delete hooks[event];
    } else {
      hooks[event] = cleanedGroups;
    }
  }

  if (Object.keys(hooks).length === 0) {
    delete cleaned.hooks;
  } else {
    cleaned.hooks = hooks;
  }
  return cleaned;
}

async function exists(
  fileSystem: ClaudeCodeAdapterFileSystem,
  filePath: string,
): Promise<boolean> {
  try {
    await fileSystem.access(filePath);
    return true;
  } catch {
    return false;
  }
}

export async function installClaudeCodeAdapter(
  options: InstallClaudeCodeAdapterOptions,
): Promise<ClaudeCodeAdapterPlan | null> {
  if (options.enabled === false) {
    return null;
  }

  const fileSystem = options.fileSystem ?? fs;
  const plan = buildClaudeCodeAdapterPlan(options);

  for (const file of plan.files) {
    await fileSystem.mkdir(path.dirname(file.filePath), { recursive: true });
    await fileSystem.writeFile(file.filePath, file.content, {
      mode: file.executable ? 0o755 : 0o644,
      encoding: "utf8",
    });
    if (file.executable && fileSystem.chmod) {
      await fileSystem.chmod(file.filePath, 0o755);
    }
  }

  await fileSystem.mkdir(path.dirname(plan.settingsPath), { recursive: true });
  const raw = await fileSystem
    .readFile(plan.settingsPath, "utf8")
    .catch(() => "{}");
  if (raw.trim().length > 0 && !(await exists(fileSystem, plan.backupPath))) {
    await fileSystem.copyFile(plan.settingsPath, plan.backupPath).catch(() => {});
  }

  let parsed: unknown;
  try {
    parsed = parseClaudeSettings(raw);
  } catch {
    parsed = {};
  }
  const merged = mergeClaudeCodeSettings(parsed, plan);
  await fileSystem.writeFile(plan.settingsPath, `${JSON.stringify(merged, null, 2)}\n`, {
    encoding: "utf8",
    mode: 0o600,
  });

  return plan;
}

export async function removeClaudeCodeAdapter(
  options: RemoveClaudeCodeAdapterOptions,
): Promise<ClaudeCodeAdapterPlan> {
  const fileSystem = options.fileSystem ?? fs;
  const plan = buildClaudeCodeAdapterPlan(options);
  const raw = await fileSystem.readFile(plan.settingsPath, "utf8").catch(() => null);

  if (raw !== null) {
    let parsed: unknown;
    try {
      parsed = parseClaudeSettings(raw);
    } catch {
      parsed = null;
    }
    if (parsed !== null) {
      const cleaned = removeClaudeCodeSettings(parsed, plan);
      await fileSystem.mkdir(path.dirname(plan.settingsPath), { recursive: true });
      await fileSystem.writeFile(
        plan.settingsPath,
        `${JSON.stringify(cleaned, null, 2)}\n`,
        {
          encoding: "utf8",
          mode: 0o600,
        },
      );
    }
  }

  if (fileSystem.rm) {
    await fileSystem.rm(plan.stateFilePath, { force: true }).catch(() => {});
    await fileSystem.rm(plan.scriptDir, { recursive: true, force: true }).catch(() => {});
  }
  return plan;
}
