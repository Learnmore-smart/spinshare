import * as fs from "node:fs/promises";
import * as path from "node:path";

export const DEFAULT_TERMINAL_AGENTS = [
  "claude",
  "agy",
  "antigravity",
] as const;

const AGENT_NAME_PATTERN = /^[A-Za-z0-9._-]+$/;
const LAUNCHER_FILE = "spinshare-terminal-launcher.cjs";
const NATIVE_ADAPTER_AGENTS = ["claude"] as const;

export interface TerminalShimFile {
  filePath: string;
  content: string;
  executable: boolean;
}

export interface TerminalAutoWrapPlan {
  shimDir: string;
  pathPrepend: string;
  files: TerminalShimFile[];
}

export interface BuildTerminalAutoWrapPlanOptions {
  storageRoot: string;
  extensionRoot: string;
  baseUrl: string;
  agents?: readonly unknown[];
  pathDelimiter?: string;
}

export interface TerminalEnvironmentCollectionLike {
  clear(): void;
  prepend(variable: string, value: string): void;
  persistent?: boolean;
  description?: unknown;
}

interface TerminalAutoWrapFileSystem {
  mkdir(filePath: string, options: { recursive: true }): Promise<unknown>;
  writeFile(
    filePath: string,
    content: string,
    options?: { mode?: number },
  ): Promise<unknown>;
  chmod?(filePath: string, mode: number): Promise<unknown>;
}

export interface InstallTerminalAutoWrapOptions
  extends BuildTerminalAutoWrapPlanOptions {
  enabled?: boolean;
  collection: TerminalEnvironmentCollectionLike;
  fileSystem?: TerminalAutoWrapFileSystem;
}

export function normalizeTerminalAgents(
  agents: readonly unknown[] | undefined,
): string[] {
  const normalized: string[] = [];
  const seen = new Set<string>();

  for (const value of agents ?? []) {
    if (typeof value !== "string") {
      continue;
    }
    const agent = value.trim();
    if (!AGENT_NAME_PATTERN.test(agent) || seen.has(agent)) {
      continue;
    }
    seen.add(agent);
    normalized.push(agent);
  }

  return normalized.length > 0 ? normalized : [...DEFAULT_TERMINAL_AGENTS];
}

function trimBaseUrl(baseUrl: string): string {
  return baseUrl.replace(/\/+$/, "");
}

function cmdShim(agent: string): string {
  return [
    "@echo off",
    `node "%~dp0${LAUNCHER_FILE}" "${agent}" %*`,
    "exit /b %ERRORLEVEL%",
    "",
  ].join("\r\n");
}

function powerShellShim(agent: string): string {
  return [
    `$launcher = Join-Path $PSScriptRoot "${LAUNCHER_FILE}"`,
    `& node $launcher "${agent}" @args`,
    "exit $LASTEXITCODE",
    "",
  ].join("\n");
}

function posixShim(agent: string): string {
  return [
    "#!/usr/bin/env sh",
    "set -eu",
    'script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)',
    `exec node "$script_dir/${LAUNCHER_FILE}" "${agent}" "$@"`,
    "",
  ].join("\n");
}

function launcherScript(extensionRoot: string, baseUrl: string): string {
  return `// Generated by SpinShare. Do not edit.
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const extensionRoot = ${JSON.stringify(extensionRoot)};
const configuredBaseUrl = ${JSON.stringify(trimBaseUrl(baseUrl))};
const nativeAdapterAgents = new Set(${JSON.stringify([...NATIVE_ADAPTER_AGENTS])});
const shimDir = __dirname;
const agent = process.argv[2];
const args = process.argv.slice(3);

if (!agent) {
  console.error("spinshare terminal launcher: missing agent command");
  process.exit(1);
}

const pathKey =
  Object.keys(process.env).find((key) => key.toLowerCase() === "path") ||
  "PATH";
const originalPath = process.env[pathKey] || "";

function normalizePath(value) {
  const resolved = path.resolve(value);
  return process.platform === "win32" ? resolved.toLowerCase() : resolved;
}

const normalizedShimDir = normalizePath(shimDir);
process.env[pathKey] = originalPath
  .split(path.delimiter)
  .filter((entry) => normalizePath(entry) !== normalizedShimDir)
  .join(path.delimiter);

if (!process.env.SPINSHARE_BASE_URL) {
  process.env.SPINSHARE_BASE_URL = configuredBaseUrl;
}
if (!process.env.SPINSHARE_API_URL) {
  process.env.SPINSHARE_API_URL = process.env.SPINSHARE_BASE_URL;
}

function exitWithResult(result, errorMessage) {
  if (result.error) {
    console.error(errorMessage + result.error.message);
    process.exit(1);
  }

  if (result.signal) {
    const signalNumber = os.constants.signals[result.signal] || 0;
    process.exit(128 + signalNumber);
  }

  process.exit(result.status == null ? 1 : result.status);
}

if (nativeAdapterAgents.has(agent)) {
  const result = spawnSync(agent, args, {
    stdio: "inherit",
    env: process.env,
    windowsHide: false,
    shell: process.platform === "win32",
  });
  exitWithResult(
    result,
    "spinshare terminal launcher: could not start " + agent + ". ",
  );
}

const cliCandidates = [
  process.env.SPINSHARE_CLI_PATH,
  path.resolve(extensionRoot, "cli-wrapper", "dist", "index.js"),
  path.resolve(extensionRoot, "..", "cli-wrapper", "dist", "index.js"),
].filter(Boolean);

let command = "spinshare";
let commandArgs = [];

for (const candidate of cliCandidates) {
  if (typeof candidate === "string" && fs.existsSync(candidate)) {
    command = process.execPath;
    commandArgs = [candidate];
    break;
  }
}

const result = spawnSync(command, [...commandArgs, agent, ...args], {
  stdio: "inherit",
  env: process.env,
  windowsHide: false,
});
exitWithResult(
  result,
  "spinshare terminal launcher: could not start SpinShare CLI. " +
    "For local development, build cli-wrapper first or set SPINSHARE_CLI_PATH. ",
);
`;
}

export function buildTerminalAutoWrapPlan(
  options: BuildTerminalAutoWrapPlanOptions,
): TerminalAutoWrapPlan {
  const agents = normalizeTerminalAgents(options.agents);
  const shimDir = path.join(options.storageRoot, "terminal-shims");
  const pathDelimiter = options.pathDelimiter ?? path.delimiter;
  const launcherPath = path.join(shimDir, LAUNCHER_FILE);
  const files: TerminalShimFile[] = [
    {
      filePath: launcherPath,
      content: launcherScript(options.extensionRoot, options.baseUrl),
      executable: false,
    },
  ];

  for (const agent of agents) {
    files.push(
      {
        filePath: path.join(shimDir, `${agent}.cmd`),
        content: cmdShim(agent),
        executable: false,
      },
      {
        filePath: path.join(shimDir, `${agent}.ps1`),
        content: powerShellShim(agent),
        executable: false,
      },
      {
        filePath: path.join(shimDir, agent),
        content: posixShim(agent),
        executable: true,
      },
    );
  }

  return {
    shimDir,
    pathPrepend: `${shimDir}${pathDelimiter}`,
    files,
  };
}

export function applyTerminalAutoWrapEnvironment(
  plan: TerminalAutoWrapPlan,
  collection: TerminalEnvironmentCollectionLike,
): void {
  collection.clear();
  collection.persistent = true;
  collection.description = "SpinShare terminal agent shims";
  collection.prepend("PATH", plan.pathPrepend);
}

export async function installTerminalAutoWrap(
  options: InstallTerminalAutoWrapOptions,
): Promise<TerminalAutoWrapPlan | null> {
  if (options.enabled === false) {
    options.collection.clear();
    return null;
  }

  const fileSystem = options.fileSystem ?? fs;
  const plan = buildTerminalAutoWrapPlan(options);

  for (const file of plan.files) {
    await fileSystem.mkdir(path.dirname(file.filePath), { recursive: true });
    await fileSystem.writeFile(file.filePath, file.content, {
      mode: file.executable ? 0o755 : 0o644,
    });
    if (file.executable && fileSystem.chmod) {
      try {
        await fileSystem.chmod(file.filePath, 0o755);
      } catch {
        // Best effort: chmod is not meaningful on every platform/filesystem.
      }
    }
  }

  applyTerminalAutoWrapEnvironment(plan, options.collection);
  return plan;
}
